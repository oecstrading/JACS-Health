import { ScrollView, Text, View, TouchableOpacity, Share, Alert } from "react-native";
import { router } from "expo-router";
import { ScreenContainer } from "@/components/screen-container";
import { useColors } from "@/hooks/use-colors";
import * as Haptics from "expo-haptics";
const REPORTS = [
  { title: "7-Day Blood Glucose Summary", icon: "🩸", desc: "Average BG, time-in-range, lows, highs, and trend chart for the last 7 days.", data: "Avg BG: 118 mg/dL | TIR: 78% | Lows: 3 | Highs: 2 | Best day: Tuesday" },
  { title: "30-Day A1C Estimate", icon: "🧪", desc: "Estimated A1C calculated from 30 days of logged readings using ADA formula.", data: "Estimated A1C: 6.8% | Target: <7.5% | Status: EXCELLENT | 847 readings analyzed" },
  { title: "Medication Adherence Report", icon: "💊", desc: "Insulin dose compliance, missed doses, and timing consistency for last 30 days.", data: "Adherence: 92% | Missed doses: 4 | On-time doses: 87% | Lantus: 97% | Humalog: 89%" },
  { title: "CGM Time-in-Range Report", icon: "📊", desc: "Detailed breakdown of time spent in target range, low, and high for last 14 days.", data: "TIR (70–180): 78% | Low (<70): 4% | High (>180): 18% | Very Low (<54): 0.5%" },
];
export default function HealthReportExportScreen() {
  const colors = useColors();
  const shareReport = async (report: typeof REPORTS[0]) => {
    Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Medium);
    const msg = `JACS Health Report — ${report.title}

${report.desc}

Data Summary:
${report.data}

Generated by JACS Health Companion
Date: ${new Date().toLocaleDateString()}`;
    await Share.share({ message: msg, title: report.title });
  };
  const shareAll = async () => {
    Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Medium);
    const msg = REPORTS.map(r => r.title + "\n" + r.data).join("\n\n---\n\n");
    await Share.share({ message: "JACS Health — Full Report\n\n" + msg + "\n\nGenerated: " + new Date().toLocaleDateString(), title: "JACS Full Health Report" });
  };
  return (
    <ScreenContainer>
      <ScrollView className="flex-1 px-4 pt-4" showsVerticalScrollIndicator={false}>
        <View className="mb-4 flex-row items-center">
          <TouchableOpacity onPress={() => router.back()} style={{ backgroundColor: colors.surface, borderRadius: 20, width: 40, height: 40, alignItems: "center", justifyContent: "center", marginRight: 12 }}>
            <Text style={{ color: colors.primary, fontSize: 16 }}>Back</Text>
          </TouchableOpacity>
          <Text className="flex-1 text-2xl font-bold text-foreground">Export Reports</Text>
        </View>
        <TouchableOpacity onPress={shareAll} style={{ backgroundColor: colors.primary, borderRadius: 16, padding: 16, alignItems: "center", marginBottom: 20 }}>
          <Text style={{ color: "#fff", fontWeight: "800", fontSize: 16 }}>📤 Share All Reports</Text>
          <Text style={{ color: "#fff", fontSize: 13, marginTop: 4, opacity: 0.9 }}>Email to endocrinologist before appointment</Text>
        </TouchableOpacity>
        {REPORTS.map((r, i) => (
          <View key={i} style={{ backgroundColor: colors.surface, borderRadius: 16, padding: 16, marginBottom: 12, borderWidth: 1, borderColor: colors.border }}>
            <Text style={{ fontSize: 28, marginBottom: 8 }}>{r.icon}</Text>
            <Text style={{ color: colors.foreground, fontWeight: "800", fontSize: 15, marginBottom: 4 }}>{r.title}</Text>
            <Text style={{ color: colors.muted, fontSize: 13, marginBottom: 8 }}>{r.desc}</Text>
            <View style={{ backgroundColor: colors.primary + "10", borderRadius: 8, padding: 10, marginBottom: 10 }}>
              <Text style={{ color: colors.foreground, fontSize: 12, fontFamily: "monospace" }}>{r.data}</Text>
            </View>
            <TouchableOpacity onPress={() => shareReport(r)} style={{ backgroundColor: colors.primary + "20", borderRadius: 10, padding: 10, alignItems: "center" }}>
              <Text style={{ color: colors.primary, fontWeight: "700" }}>📤 Share This Report</Text>
            </TouchableOpacity>
          </View>
        ))}
        <View style={{ height: 24 }} />
      </ScrollView>
    </ScreenContainer>
  );
}
