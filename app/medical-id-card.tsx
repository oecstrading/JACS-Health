/**
 * Medical ID Card — Type 1 Diabetes Emergency Card
 *
 * Designed to be:
 * - Printed and laminated for teachers, coaches, babysitters
 * - Shared digitally with school nurses
 * - Displayed on lock screen in emergencies
 *
 * Per ADA Safe at School 2024 and JDRF guidelines
 */

import React, { useState } from "react";
import {
  View,
  Text,
  ScrollView,
  TouchableOpacity,
  StyleSheet,
  Share,
  TextInput,
  Alert,
} from "react-native";
import { ScreenContainer } from "@/components/screen-container";
import { useColors } from "@/hooks/use-colors";
import { router } from "expo-router";
import AsyncStorage from "@react-native-async-storage/async-storage";

interface MedicalIDData {
  childName: string;
  dateOfBirth: string;
  diagnosisDate: string;
  insulinType: string;
  insulinToCarb: string;
  correctionFactor: string;
  targetGlucose: string;
  lowThreshold: string;
  highThreshold: string;
  pumpType: string;
  cgmType: string;
  glucagonLocation: string;
  parent1Name: string;
  parent1Phone: string;
  parent2Name: string;
  parent2Phone: string;
  endoName: string;
  endoPhone: string;
  allergies: string;
  otherConditions: string;
  fastCarbSource: string;
}

const DEFAULT_DATA: MedicalIDData = {
  childName: "",
  dateOfBirth: "",
  diagnosisDate: "",
  insulinType: "Humalog / NovoLog",
  insulinToCarb: "1:15",
  correctionFactor: "1:50",
  targetGlucose: "100–150 mg/dL",
  lowThreshold: "70",
  highThreshold: "250",
  pumpType: "Omnipod DASH",
  cgmType: "Dexcom G7",
  glucagonLocation: "Nurse's office + classroom emergency kit",
  parent1Name: "",
  parent1Phone: "",
  parent2Name: "",
  parent2Phone: "",
  endoName: "",
  endoPhone: "",
  allergies: "None known",
  otherConditions: "None",
  fastCarbSource: "Juice boxes (15g), glucose tablets",
};

const STORAGE_KEY = "@medical_id_card";

export default function MedicalIDCard() {
  const colors = useColors();
  const [editing, setEditing] = useState(false);
  const [data, setData] = useState<MedicalIDData>(DEFAULT_DATA);
  const [saved, setSaved] = useState(false);

  React.useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY).then(raw => {
      if (raw) {
        try { setData(JSON.parse(raw)); } catch (_) {}
      }
    });
  }, []);

  const save = async () => {
    await AsyncStorage.setItem(STORAGE_KEY, JSON.stringify(data));
    setSaved(true);
    setEditing(false);
    setTimeout(() => setSaved(false), 2000);
  };

  const handleShare = async () => {
    const card = `
╔══════════════════════════════════════╗
       🩸 TYPE 1 DIABETES MEDICAL ID CARD
╚══════════════════════════════════════╝

CHILD: ${data.childName}
DOB: ${data.dateOfBirth}   DIAGNOSED: ${data.diagnosisDate}

── DEVICES ──
CGM: ${data.cgmType}
Insulin Pump: ${data.pumpType}

── INSULIN DOSES ──
Insulin-to-Carb Ratio: ${data.insulinToCarb}
Correction Factor: ${data.correctionFactor}
Target Glucose: ${data.targetGlucose}
Low Alert: <${data.lowThreshold} mg/dL
High Alert: >${data.highThreshold} mg/dL

── EMERGENCY TREATMENT ──
LOW BLOOD SUGAR (<${data.lowThreshold} mg/dL):
Give ${data.fastCarbSource} IMMEDIATELY.
Wait 15 min. Recheck. Repeat if needed.
If unconscious → CALL 911 + give glucagon.

GLUCAGON LOCATION: ${data.glucagonLocation}

── EMERGENCY CONTACTS ──
${data.parent1Name}: ${data.parent1Phone}
${data.parent2Name}: ${data.parent2Phone}
Endocrinologist (${data.endoName}): ${data.endoPhone}

── ALLERGIES ──
${data.allergies}

── OTHER CONDITIONS ──
${data.otherConditions}

This child has Type 1 Diabetes. Their pancreas produces NO insulin.
They require insulin for every meal. This is life-critical.

Generated by JACS Health Companion
    `.trim();

    try {
      await Share.share({ title: `${data.childName} — Diabetes Medical ID`, message: card });
    } catch (_) {}
  };

  const field = (label: string, key: keyof MedicalIDData, placeholder?: string) => (
    <View style={styles.fieldRow} key={key}>
      <Text style={[styles.fieldLabel, { color: colors.muted }]}>{label}</Text>
      {editing ? (
        <TextInput
          style={[styles.fieldInput, { color: colors.foreground, borderColor: colors.border, backgroundColor: colors.surface }]}
          value={data[key]}
          onChangeText={v => setData(d => ({ ...d, [key]: v }))}
          placeholder={placeholder ?? label}
          placeholderTextColor={colors.muted}
        />
      ) : (
        <Text style={[styles.fieldValue, { color: colors.foreground }]}>{data[key] || "—"}</Text>
      )}
    </View>
  );

  return (
    <ScreenContainer>
      {/* Header */}
      <View style={[styles.header, { backgroundColor: "#DC2626" }]}>
        <TouchableOpacity onPress={() => router.back()}>
          <Text style={styles.headerBack}>‹ Back</Text>
        </TouchableOpacity>
        <Text style={styles.headerTitle}>🪪 Medical ID Card</Text>
        <TouchableOpacity onPress={() => editing ? save() : setEditing(true)}>
          <Text style={styles.headerAction}>{editing ? "Save" : "Edit"}</Text>
        </TouchableOpacity>
      </View>

      {saved && (
        <View style={[styles.savedBanner, { backgroundColor: "#22C55E" }]}>
          <Text style={{ color: "#fff", fontWeight: "700", textAlign: "center" }}>✓ Saved successfully</Text>
        </View>
      )}

      <ScrollView contentContainerStyle={styles.scroll} showsVerticalScrollIndicator={false}>

        {/* Card Preview */}
        <View style={[styles.idCard, { backgroundColor: "#DC2626" }]}>
          <View style={styles.idCardHeader}>
            <Text style={styles.idCardIcon}>🩸</Text>
            <View>
              <Text style={styles.idCardTitle}>TYPE 1 DIABETES</Text>
              <Text style={styles.idCardSub}>Medical Emergency Card</Text>
            </View>
          </View>
          <Text style={styles.idCardName}>{data.childName || "Child's Name"}</Text>
          <View style={styles.idCardRow}>
            <Text style={styles.idCardLabel}>DOB</Text>
            <Text style={styles.idCardVal}>{data.dateOfBirth || "—"}</Text>
            <Text style={styles.idCardLabel}>Diagnosed</Text>
            <Text style={styles.idCardVal}>{data.diagnosisDate || "—"}</Text>
          </View>
          <View style={[styles.idCardAlert, { backgroundColor: "rgba(0,0,0,0.3)" }]}>
            <Text style={styles.idCardAlertText}>
              ⚠️ LOW SUGAR: Give {data.fastCarbSource || "15g fast carbs"} NOW
            </Text>
            <Text style={styles.idCardAlertText}>
              🚨 UNCONSCIOUS: Call 911 + Glucagon at {data.glucagonLocation || "nurse's office"}
            </Text>
          </View>
          <View style={styles.idCardContacts}>
            <Text style={styles.idCardContactLabel}>📞 {data.parent1Name || "Parent 1"}: {data.parent1Phone || "—"}</Text>
            <Text style={styles.idCardContactLabel}>📞 {data.parent2Name || "Parent 2"}: {data.parent2Phone || "—"}</Text>
          </View>
        </View>

        {/* Share Button */}
        <TouchableOpacity
          style={[styles.shareBtn, { backgroundColor: "#1D4ED8" }]}
          onPress={handleShare}
        >
          <Text style={styles.shareBtnText}>📤 Share / Print Card</Text>
        </TouchableOpacity>

        <Text style={[styles.sectionTitle, { color: colors.foreground }]}>Child Information</Text>
        {field("Child's Full Name", "childName", "e.g. Emma Johnson")}
        {field("Date of Birth", "dateOfBirth", "e.g. Jan 15, 2021")}
        {field("Diagnosis Date", "diagnosisDate", "e.g. March 2022")}

        <Text style={[styles.sectionTitle, { color: colors.foreground }]}>Devices</Text>
        {field("CGM Device", "cgmType", "e.g. Dexcom G7")}
        {field("Insulin Pump", "pumpType", "e.g. Omnipod DASH / None")}

        <Text style={[styles.sectionTitle, { color: colors.foreground }]}>Insulin Dosing</Text>
        {field("Insulin Type", "insulinType", "e.g. Humalog")}
        {field("Insulin-to-Carb Ratio", "insulinToCarb", "e.g. 1:15 (1 unit per 15g carbs)")}
        {field("Correction Factor", "correctionFactor", "e.g. 1:50 (1 unit drops BG by 50)")}
        {field("Target Glucose", "targetGlucose", "e.g. 100–150 mg/dL")}
        {field("Low Alert Threshold", "lowThreshold", "e.g. 70")}
        {field("High Alert Threshold", "highThreshold", "e.g. 250")}

        <Text style={[styles.sectionTitle, { color: colors.foreground }]}>Emergency Treatment</Text>
        {field("Fast Carb Source", "fastCarbSource", "e.g. Juice boxes, glucose tablets")}
        {field("Glucagon Kit Location", "glucagonLocation", "e.g. Nurse's office")}

        <Text style={[styles.sectionTitle, { color: colors.foreground }]}>Emergency Contacts</Text>
        {field("Parent/Guardian 1 Name", "parent1Name")}
        {field("Parent/Guardian 1 Phone", "parent1Phone", "e.g. +1 555-0100")}
        {field("Parent/Guardian 2 Name", "parent2Name")}
        {field("Parent/Guardian 2 Phone", "parent2Phone", "e.g. +1 555-0101")}
        {field("Endocrinologist Name", "endoName")}
        {field("Endocrinologist Phone", "endoPhone")}

        <Text style={[styles.sectionTitle, { color: colors.foreground }]}>Medical History</Text>
        {field("Allergies", "allergies", "e.g. Penicillin, None")}
        {field("Other Conditions", "otherConditions", "e.g. Celiac disease, None")}

        {editing && (
          <TouchableOpacity
            style={[styles.saveBtn, { backgroundColor: "#22C55E" }]}
            onPress={save}
          >
            <Text style={styles.saveBtnText}>✓ Save Medical ID Card</Text>
          </TouchableOpacity>
        )}

        <View style={[styles.disclaimer, { backgroundColor: colors.surface, borderColor: colors.border }]}>
          <Text style={[styles.disclaimerText, { color: colors.muted }]}>
            Print this card and laminate it. Give copies to: classroom teacher, PE teacher, school nurse, after-school care, sports coaches, and any regular babysitters or family members.
          </Text>
        </View>

        <View style={{ height: 40 }} />
      </ScrollView>
    </ScreenContainer>
  );
}

const styles = StyleSheet.create({
  header: { flexDirection: "row", justifyContent: "space-between", alignItems: "center", padding: 16 },
  headerBack: { color: "#fff", fontSize: 16, fontWeight: "600" },
  headerTitle: { color: "#fff", fontSize: 17, fontWeight: "800" },
  headerAction: { color: "#fff", fontSize: 14, fontWeight: "700", backgroundColor: "rgba(255,255,255,0.25)", paddingHorizontal: 12, paddingVertical: 6, borderRadius: 16 },
  savedBanner: { padding: 10 },
  scroll: { padding: 16 },
  idCard: { borderRadius: 20, padding: 20, marginBottom: 16 },
  idCardHeader: { flexDirection: "row", alignItems: "center", gap: 12, marginBottom: 12 },
  idCardIcon: { fontSize: 36 },
  idCardTitle: { color: "#fff", fontSize: 20, fontWeight: "900", letterSpacing: 1 },
  idCardSub: { color: "rgba(255,255,255,0.8)", fontSize: 13 },
  idCardName: { color: "#fff", fontSize: 26, fontWeight: "900", marginBottom: 10 },
  idCardRow: { flexDirection: "row", gap: 16, marginBottom: 12 },
  idCardLabel: { color: "rgba(255,255,255,0.7)", fontSize: 11, fontWeight: "700" },
  idCardVal: { color: "#fff", fontSize: 13, fontWeight: "600", marginRight: 8 },
  idCardAlert: { borderRadius: 12, padding: 12, marginBottom: 12, gap: 6 },
  idCardAlertText: { color: "#fff", fontSize: 12, fontWeight: "700", lineHeight: 18 },
  idCardContacts: { gap: 4 },
  idCardContactLabel: { color: "rgba(255,255,255,0.9)", fontSize: 13 },
  shareBtn: { borderRadius: 14, padding: 16, alignItems: "center", marginBottom: 24 },
  shareBtnText: { color: "#fff", fontSize: 16, fontWeight: "800" },
  sectionTitle: { fontSize: 16, fontWeight: "800", marginTop: 20, marginBottom: 10 },
  fieldRow: { marginBottom: 12 },
  fieldLabel: { fontSize: 12, fontWeight: "600", marginBottom: 4 },
  fieldValue: { fontSize: 15, fontWeight: "500" },
  fieldInput: { borderWidth: 1.5, borderRadius: 10, padding: 12, fontSize: 15 },
  saveBtn: { borderRadius: 14, padding: 16, alignItems: "center", marginTop: 24, marginBottom: 8 },
  saveBtnText: { color: "#fff", fontSize: 16, fontWeight: "800" },
  disclaimer: { borderRadius: 12, borderWidth: 1, padding: 14, marginTop: 16 },
  disclaimerText: { fontSize: 13, lineHeight: 20 },
});
