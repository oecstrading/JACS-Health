import { TouchableOpacity, Text, Alert, Platform } from "react-native";
import * as MailComposer from "expo-mail-composer";
import * as SMS from "expo-sms";
import { useColors } from "@/hooks/use-colors";
import { IconSymbol } from "@/components/ui/icon-symbol";

interface ReportShareButtonProps {
  report: string;
  title: string;
  type?: "email" | "sms";
}

/**
 * Report Share Button Component
 * Allows sharing of medical reports via email or SMS
 */
export function ReportShareButton({ report, title, type = "email" }: ReportShareButtonProps) {
  const colors = useColors();

  const shareViaEmail = async () => {
    try {
      const isAvailable = await MailComposer.isAvailableAsync();
      if (!isAvailable) {
        Alert.alert("Error", "Email is not available on this device");
        return;
      }

      await MailComposer.composeAsync({
        subject: `Medical Report: ${title}`,
        body: `${report}\n\n---\nGenerated by HealthMate AI Analysis\nThis report is for informational purposes only and should be reviewed by a qualified healthcare provider.`,
        isHtml: false,
      });
    } catch (error) {
      Alert.alert("Error", "Failed to open email composer");
    }
  };

  const shareViaSMS = async () => {
    try {
      const isAvailable = await SMS.isAvailableAsync();
      if (!isAvailable) {
        Alert.alert("Error", "SMS is not available on this device");
        return;
      }

      const message = `Medical Report: ${title}\n\n${report.substring(0, 500)}...\n\nView full report in HealthMate app`;

      await SMS.sendSMSAsync([], message);
    } catch (error) {
      Alert.alert("Error", "Failed to open SMS composer");
    }
  };

  const handleShare = () => {
    if (type === "email") {
      shareViaEmail();
    } else {
      shareViaSMS();
    }
  };

  return (
    <TouchableOpacity
      onPress={handleShare}
      className="flex-row items-center gap-2 bg-primary px-4 py-2 rounded-lg"
    >
      <IconSymbol 
        name="paperplane.fill" 
        size={16} 
        color="white"
      />
      <Text className="text-white font-semibold">
        Share via {type === "email" ? "Email" : "SMS"}
      </Text>
    </TouchableOpacity>
  );
}
